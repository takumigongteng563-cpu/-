// 新しく条件がそろったイベントを起こす
export function checkEvents(game, helpers) {
  for (const ev of EVENTS) {
    if (game.firedEvents.includes(ev.id)) continue;
    if (game.day < ev.day) continue;
    if (!ev.cond(game)) continue;
    const lines = ev.linesFor ? ev.linesFor(game) : ev.lines;
    if (ev.effect) ev.effect(game, helpers);
    game.firedEvents.push(ev.id);
    game.eventLog.push({ id: ev.id, day: game.day, title: ev.title, lines });
    game.log.push(`《イベント》${ev.title}`);
  }
}
